// type.js: song timing, typography, crisp 2D graphics and the text registry.
//
// Added for the interp music video; not part of the original ClaudeAnimationBase kit. The guide's "no text" rule is
// deliberately overridden here: the lyrics carry the jargon (singers blur "logit lens"), so text is a first-class layer.
//
// Everything is still a pure function of t. Text and 2D graphics are queued on LETTERS as Canvas2D draw ops, so they
// follow the kit's layering: they land on top of whatever the shot has painted so far, follow an active camera (pass
// {screen: true} to opt out), and flushLetters() before a wipe puts them under the wipe.
//
// Every piece of text drawn through tx() is recorded in TEXTREG with its on-screen box, so window.textCheck() can flag
// overlaps, text outside the title-safe area, text too small or too low-contrast to read, and reads that flash by.

// ---------- song timing (SONG comes from src/data/song*.js, generated by tools/song_js.py) ----------
const HAS_SONG = typeof SONG !== 'undefined';
const barN = t => Math.floor(bpOf(t) / 4);                     // bar index (bar 0 starts at the first downbeat)
const beatInBar = t => ((beatN(t) % 4) + 4) % 4;                // 0..3; 0 is the downbeat
const barFrac = t => frac(bpOf(t) / 4);                         // 0..1 progress through the current bar
const beatT = n => OFF + n * BEAT;                              // time of beat n
const barT = n => OFF + n * 4 * BEAT;                           // time of bar n's downbeat
// Index of the last element of a sorted array <= x (or -1). Used on event-time lists.
function lastLE(arr, x, key = v => v) { let lo = 0, hi = arr.length - 1, r = -1; while (lo <= hi) { const m = (lo + hi) >> 1; if (key(arr[m]) <= x) { r = m; lo = m + 1; } else hi = m - 1; } return r; }
// 1 at each event time in `times` (sorted), decaying after it: pulse() for arbitrary events (word onsets, hits).
function hitPulse(t, times, k = 8) { const i = lastLE(times, t); return i < 0 ? 0 : Math.exp(-(t - times[i]) * k); }
// The SONG line being sung at t, or null. hold: seconds a line stays "current" after its last word ends; early: seconds
// before its first word it becomes current (subtitle preview: 4-6 frames early and dim, per refs/video_craft.md §2.2).
function lineAt(t, hold = .25, early = 0) {
  if (!HAS_SONG) return null;
  const L = SONG.lines.filter(l => l.t0 != null), i = lastLE(L, t + early, l => l.t0);
  if (i < 0) return null;
  const l = L[i]; return t <= l.t1 + hold ? l : null;
}
const lineByIdx = i => HAS_SONG ? SONG.lines.find(l => l.i === i) : null;
function sectionAt(t) { if (!HAS_SONG) return null; const i = lastLE(SONG.sections, t, s => s.t0); return i < 0 ? null : SONG.sections[i]; }
// The display word being sung at t within a line (index), or -1 before the first word.
const wordIdxAt = (line, t) => lastLE(line.words, t, w => w.t0 ?? Infinity);
// Loudness 0..1 at t (10 Hz RMS, normalised to the song's 98th percentile) for audio-reactive motion.
let _rmsMax = null;
function loud(t) {
  if (!HAS_SONG) return 0;
  if (_rmsMax == null) { const s = [...SONG.rms10].sort((a, b) => a - b); _rmsMax = s[Math.floor(s.length * .98)] || 1; }
  const x = t * 10, i = Math.floor(x), a = SONG.rms10[i] ?? 0, b = SONG.rms10[i + 1] ?? a;
  return clamp(lerp(a, b, x - i) / _rmsMax);
}

